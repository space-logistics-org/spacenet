"""
Object schemas for the results of demand analyses.
"""

from typing import Dict, List, Optional
from uuid import UUID

from fastapi_camelcase import CamelModel
from pydantic import Field

from ...schemas import ClassOfSupply, Environment, Scenario
from ..elements import SimElement
from ..errors import SimDemand
from ..network import SimLocation
from ..resources import Demand, DemandSet, SimResource
from ..simulator import DemandSimulator
from .issues import SimIssue, collect_issues


class DemandLocation(CamelModel):
    """
    Location referenced by a demand.
    """

    id: UUID = Field(..., description="Unique identifier")
    name: str = Field(..., description="Location name")

    @classmethod
    def create(cls, location: Optional[SimLocation]) -> Optional["DemandLocation"]:
        """Creates a reference to a location."""
        if location is None:
            return None
        return cls(id=location.id, name=location.name)


class DemandElement(CamelModel):
    """
    Element referenced by a demand.
    """

    id: UUID = Field(..., description="Unique identifier")
    name: str = Field(..., description="Element name")

    @classmethod
    def create(cls, element: Optional[SimElement]) -> Optional["DemandElement"]:
        """Creates a reference to an element."""
        if element is None:
            return None
        return cls(id=element.id, name=element.name)


class DemandResourceType(CamelModel):
    """
    Resource type referenced by a demand.
    """

    type: str = Field(
        ..., description="Resource type (Generic, Continuous, or Discrete)"
    )
    name: str = Field(..., description="Resource name")
    class_of_supply: ClassOfSupply = Field(..., description="Class of supply")
    environment: Environment = Field(..., description="Required stowage environment")
    units: str = Field(..., description="Unit resource label")
    unit_mass: float = Field(..., description="Mass (kg) of 1.0 units")
    unit_volume: float = Field(..., description="Volume (m^3) of 1.0 units")
    packing_factor: float = Field(
        ..., description="Mass (kg) of packing material required per unit"
    )

    @classmethod
    def create(cls, resource: SimResource) -> "DemandResourceType":
        """Creates a description of a resource."""
        return cls(
            type=resource.resource_type,
            name=resource.name,
            class_of_supply=resource.class_of_supply,
            environment=resource.environment,
            units=resource.units,
            unit_mass=resource.unit_mass,
            unit_volume=resource.unit_volume,
            packing_factor=resource.packing_factor,
        )


class DemandResource(CamelModel):
    """
    Demanded (consumed or produced) amount of a resource.
    """

    resource: DemandResourceType = Field(..., description="Resource type")
    amount: float = Field(..., description="Absolute amount (units)")
    mass: float = Field(..., description="Mass (kg), negative if produced")
    volume: float = Field(..., description="Volume (m^3), negative if produced")

    @classmethod
    def create(cls, demand: Demand) -> "DemandResource":
        """Creates a description of a demand."""
        return cls(
            resource=DemandResourceType.create(demand.resource),
            amount=abs(demand.amount),
            mass=demand.mass,
            volume=demand.volume,
        )


class _DemandTotals(CamelModel):
    """
    Base class for a set of consumed and produced resources.
    """

    consumption: List[DemandResource] = Field([], description="Consumed resources")
    production: List[DemandResource] = Field([], description="Produced resources")
    total_consumption_mass: float = Field(0.0, description="Mass (kg) consumed")
    total_consumption_volume: float = Field(0.0, description="Volume (m^3) consumed")
    total_production_mass: float = Field(0.0, description="Mass (kg) produced")
    total_production_volume: float = Field(0.0, description="Volume (m^3) produced")

    def _set_demands(self, demands: DemandSet):
        self.consumption = [DemandResource.create(d) for d in demands if d.amount > 0]
        self.production = [DemandResource.create(d) for d in demands if d.amount < 0]
        self.total_consumption_mass = sum(r.mass for r in self.consumption)
        self.total_consumption_volume = sum(r.volume for r in self.consumption)
        self.total_production_mass = sum(r.mass for r in self.production)
        self.total_production_volume = sum(r.volume for r in self.production)
        return self


class RawDemand(_DemandTotals):
    """
    Demands generated by an element (or mission) at a time and location.
    """

    time: float = Field(..., description="Time (days) relative to the scenario start")
    location: Optional[DemandLocation] = Field(None, description="Demand location")
    element: Optional[DemandElement] = Field(
        None, description="Demanding element (undefined for mission-level demands)"
    )

    @classmethod
    def create(cls, demand: SimDemand) -> "RawDemand":
        """Creates a description of a logged demand."""
        # pylint: disable=protected-access
        return cls(
            time=demand.time,
            location=DemandLocation.create(demand.location),
            element=DemandElement.create(demand.element),
        )._set_demands(demand.demands)


class RawDemandsAnalysis(CamelModel):
    """
    Demands logged by a demand simulator.
    """

    demands: List[RawDemand] = Field([], description="Logged demands in order of time")

    @classmethod
    def create(cls, simulator: DemandSimulator) -> "RawDemandsAnalysis":
        """
        Creates a raw demands analysis from an executed demand simulator.

        Args:
            simulator (:obj:`DemandSimulator`): The demand simulator.

        Returns:
            :obj:`RawDemandsAnalysis`: The analysis results.
        """
        return cls(demands=[RawDemand.create(d) for d in simulator.unsatisfied_demands])


class NodeDemand(_DemandTotals):
    """
    Demands aggregated to the arrival of a transport at a node.
    """

    time: float = Field(
        ..., description="Arrival time (days) relative to the scenario start"
    )
    location: DemandLocation = Field(
        ..., description="Node at which demands are supplied"
    )


class EdgeDemand(_DemandTotals):
    """
    Demands aggregated to a transport along an edge.
    """

    start_time: float = Field(..., description="Departure time (days)")
    end_time: float = Field(..., description="Arrival time (days)")
    origin: DemandLocation = Field(..., description="Origin node of the edge")
    destination: DemandLocation = Field(..., description="Destination node of the edge")
    location: DemandLocation = Field(..., description="Edge along which demands occur")
    max_cargo_mass: float = Field(..., description="Cargo mass capacity (kg)")
    net_cargo_mass: float = Field(..., description="Unused cargo mass capacity (kg)")
    max_cargo_volume: float = Field(..., description="Cargo volume capacity (m^3)")
    net_cargo_volume: float = Field(
        ..., description="Unused cargo volume capacity (m^3)"
    )


class AggregatedDemandsAnalysis(CamelModel):
    """
    Demands aggregated to the transports from which they could be supplied.
    """

    nodes: List[NodeDemand] = Field([], description="Demands aggregated to nodes")
    edges: List[EdgeDemand] = Field([], description="Demands aggregated to edges")

    @classmethod
    def create(cls, simulator: DemandSimulator) -> "AggregatedDemandsAnalysis":
        """
        Creates an aggregated demands analysis from an executed demand simulator.

        Args:
            simulator (:obj:`DemandSimulator`): The demand simulator.

        Returns:
            :obj:`AggregatedDemandsAnalysis`: The analysis results.
        """
        # pylint: disable=protected-access
        return cls(
            nodes=[
                NodeDemand(
                    time=point.time, location=DemandLocation.create(point.node)
                )._set_demands(demands)
                for point, demands in simulator.aggregated_node_demands
            ],
            edges=[
                EdgeDemand(
                    start_time=edge.start_time,
                    end_time=edge.end_time,
                    origin=DemandLocation.create(edge.edge.origin),
                    destination=DemandLocation.create(edge.edge.destination),
                    location=DemandLocation.create(edge.edge),
                    max_cargo_mass=edge.max_cargo_mass,
                    net_cargo_mass=edge.net_cargo_mass,
                    max_cargo_volume=edge.max_cargo_volume,
                    net_cargo_volume=edge.net_cargo_volume,
                )._set_demands(demands)
                for edge, demands in simulator.aggregated_edge_demands
            ],
        )


class SupplyEdgeSummary(CamelModel):
    """
    Capacity of and demands aggregated to a transport along an edge.
    """

    key: str = Field(..., description="Key which identifies the supply edge")
    location: DemandLocation = Field(..., description="Network edge")
    origin: DemandLocation = Field(..., description="Node of departure")
    destination: DemandLocation = Field(..., description="Node of arrival")
    start_time: float = Field(..., description="Departure time (days)")
    end_time: float = Field(..., description="Arrival time (days)")
    raw_capacity: float = Field(0.0, description="Cargo mass capacity (kg)")
    remaining_capacity: float = Field(
        0.0, description="Unused cargo mass capacity (kg)"
    )
    demand_mass: float = Field(
        0.0, description="Mass (kg) of demands during the transport"
    )
    net_capacity: float = Field(
        0.0, description="Unused cargo mass capacity (kg) less demands (kg)"
    )


class SupplyPointSummary(CamelModel):
    """
    Demands aggregated to the arrival of a transport at a node.
    """

    key: str = Field(..., description="Key which identifies the supply point")
    location: DemandLocation = Field(..., description="Node")
    time: float = Field(..., description="Arrival time (days)")
    demand_mass: float = Field(0.0, description="Mass (kg) of aggregated demands")


class FeasibilityPoint(CamelModel):
    """
    Cumulative capacity delivered to and demands at a node after an arrival.
    """

    time: float = Field(..., description="Arrival time (days)")
    raw_capacity: float = Field(0.0, description="Cargo mass capacity (kg)")
    remaining_capacity: float = Field(0.0, description="Unused capacity (kg)")
    demand_mass: float = Field(0.0, description="Mass (kg) of demands")
    cumulative_raw_capacity: float = Field(0.0, description="Cumulative capacity (kg)")
    cumulative_remaining_capacity: float = Field(
        0.0, description="Cumulative unused capacity (kg)"
    )
    cumulative_demand_mass: float = Field(0.0, description="Cumulative demands (kg)")


class NodeFeasibility(CamelModel):
    """
    Capacity delivered to a node compared to the demands at the node over time.
    """

    location: DemandLocation = Field(..., description="Node")
    points: List[FeasibilityPoint] = Field([], description="Arrivals in order of time")


class DemandSeries(CamelModel):
    """
    Cumulative demanded mass of one class of supply over time.
    """

    class_of_supply: int = Field(..., description="Top-level class of supply")
    points: List[List[float]] = Field(
        [], description="Pairs of time (days) and cumulative mass (kg)"
    )


class DemandSource(CamelModel):
    """
    Demands of one source (element, mission, or location) by class of supply.
    """

    id: str = Field(..., description="Identifier of the source")
    name: str = Field(..., description="Name of the source")
    total_mass: float = Field(0.0, description="Total demanded mass (kg)")
    mass_by_class_of_supply: Dict[int, float] = Field(
        {}, description="Demanded mass (kg) by top-level class of supply"
    )
    series: List[DemandSeries] = Field(
        [], description="Cumulative demanded mass over time by class of supply"
    )

    @classmethod
    def create(
        cls, source_id, name: str, history: List[SimDemand]
    ) -> Optional["DemandSource"]:
        """Creates the demands of a source from its logged demands."""
        totals: Dict[int, float] = {}
        series: Dict[int, List[List[float]]] = {}
        for sim_demand in sorted(history, key=lambda d: d.time):
            masses: Dict[int, float] = {}
            for demand in sim_demand.demands:
                base = demand.resource.class_of_supply.get_base_class()
                key = 0 if base is None else int(base)
                masses[key] = masses.get(key, 0.0) + demand.mass
            for key, mass in masses.items():
                totals[key] = totals.get(key, 0.0) + mass
                points = series.setdefault(key, [])
                if points and points[-1][0] == sim_demand.time:
                    points[-1][1] = totals[key]
                else:
                    points.append([sim_demand.time, totals[key]])
        if not totals:
            return None
        return cls(
            id=str(source_id),
            name=name,
            total_mass=sum(totals.values()),
            mass_by_class_of_supply=dict(sorted(totals.items())),
            series=[
                DemandSeries(class_of_supply=key, points=points)
                for key, points in sorted(series.items())
            ],
        )


class DemandsAnalysis(CamelModel):
    """
    Demands of a scenario: logged demands, demands aggregated to the supply
    network, and demands by element, mission, and location.
    """

    raw: RawDemandsAnalysis = Field(..., description="Logged demands")
    aggregated: AggregatedDemandsAnalysis = Field(..., description="Aggregated demands")
    supply_edges: List[SupplyEdgeSummary] = Field([], description="Transports")
    supply_points: List[SupplyPointSummary] = Field([], description="Arrivals")
    feasibility: List[NodeFeasibility] = Field(
        [], description="Capacity compared to demands at each supplied node"
    )
    by_element: List[DemandSource] = Field([], description="Demands by element")
    by_mission: List[DemandSource] = Field([], description="Demands by mission")
    by_location: List[DemandSource] = Field([], description="Demands by location")
    nodes: List[DemandLocation] = Field([], description="Network nodes")
    issues: List[SimIssue] = Field([], description="Errors and warnings")
    end_time: float = Field(0.0, description="Time (days) of the last event")
    total_mass: float = Field(0.0, description="Total demanded mass (kg)")
    unassigned_mass: float = Field(
        0.0, description="Demanded mass (kg) without a transport to supply it"
    )

    @staticmethod
    def simulate(
        scenario: Scenario,
        *,
        estimate_container_masses: bool = False,
        consume_existing_resources: bool = False,
    ) -> DemandSimulator:
        """
        Executes a demand simulator for a scenario.

        Args:
            scenario (:obj:`Scenario`): The scenario.
            estimate_container_masses (bool): True, to add demands for
                packing material (generic COS 5).
            consume_existing_resources (bool): True, to satisfy demands with
                resources available in the scenario.

        Returns:
            :obj:`DemandSimulator`: The executed simulator.
        """
        simulator = DemandSimulator(
            scenario,
            demands_satisfied=consume_existing_resources,
            packing_demands_added=estimate_container_masses,
        )
        simulator.simulate()
        return simulator

    @classmethod
    def create(cls, simulator: DemandSimulator) -> "DemandsAnalysis":
        """
        Creates a demands analysis from an executed demand simulator.

        Args:
            simulator (:obj:`DemandSimulator`): The demand simulator.

        Returns:
            :obj:`DemandsAnalysis`: The analysis results.
        """
        # pylint: disable=too-many-locals,import-outside-toplevel
        from ..manifest import edge_key, point_key

        node_demands = {
            id(p): d.total_mass for p, d in simulator.aggregated_node_demands
        }
        edge_demands = {
            id(e): d.total_mass for e, d in simulator.aggregated_edge_demands
        }
        supply_edges = [
            SupplyEdgeSummary(
                key=edge_key(e.edge.id, e.start_time, e.is_reversed),
                location=DemandLocation.create(e.edge),
                origin=DemandLocation.create(e.origin),
                destination=DemandLocation.create(e.destination),
                start_time=e.start_time,
                end_time=e.end_time,
                raw_capacity=e.max_cargo_mass,
                remaining_capacity=e.net_cargo_mass,
                demand_mass=edge_demands.get(id(e), 0.0),
                net_capacity=e.net_cargo_mass - edge_demands.get(id(e), 0.0),
            )
            for e in sorted(simulator.supply_edges, key=lambda e: e.start_time)
        ]
        supply_points = [
            SupplyPointSummary(
                key=point_key(p.node.id, p.time),
                location=DemandLocation.create(p.node),
                time=p.time,
                demand_mass=node_demands.get(id(p), 0.0),
            )
            for p in sorted(simulator.supply_points, key=lambda p: p.time)
        ]
        feasibility = []
        for node in simulator.state.network.nodes:
            times = sorted(
                {e.end_time for e in simulator.supply_edges if e.destination == node}
            )
            if not times:
                continue
            points = []
            totals = [0.0, 0.0, 0.0]
            for time in times:
                edges = [
                    e
                    for e in simulator.supply_edges
                    if e.destination == node and e.end_time == time
                ]
                raw = sum(e.max_cargo_mass for e in edges)
                remaining = sum(e.net_cargo_mass for e in edges)
                demand = sum(edge_demands.get(id(e), 0.0) for e in edges) + sum(
                    node_demands.get(id(p), 0.0)
                    for p in simulator.supply_points
                    if p.node == node and p.time == time
                )
                totals = [totals[0] + raw, totals[1] + remaining, totals[2] + demand]
                points.append(
                    FeasibilityPoint(
                        time=time,
                        raw_capacity=raw,
                        remaining_capacity=remaining,
                        demand_mass=demand,
                        cumulative_raw_capacity=totals[0],
                        cumulative_remaining_capacity=totals[1],
                        cumulative_demand_mass=totals[2],
                    )
                )
            feasibility.append(
                NodeFeasibility(location=DemandLocation.create(node), points=points)
            )

        state = simulator.state
        by_element = [
            DemandSource.create(e.id, e.name, simulator.get_demand_history(e))
            for e in sorted(state.elements.values(), key=lambda e: e.sort_key)
        ]
        by_mission = [
            DemandSource.create(m.index, m.name, simulator.get_demand_history(m))
            for m in state.missions
        ]
        by_location = [
            DemandSource.create(l.id, l.name, simulator.get_demand_history(l))
            for l in state.network.locations
        ]
        return cls(
            raw=RawDemandsAnalysis.create(simulator),
            aggregated=AggregatedDemandsAnalysis.create(simulator),
            supply_edges=supply_edges,
            supply_points=supply_points,
            feasibility=feasibility,
            by_element=[s for s in by_element if s is not None],
            by_mission=[s for s in by_mission if s is not None],
            by_location=[s for s in by_location if s is not None],
            nodes=[DemandLocation.create(n) for n in state.network.nodes],
            issues=collect_issues(simulator, demands=False),
            end_time=simulator.time,
            total_mass=sum(d.demands.total_mass for d in simulator.unsatisfied_demands),
            unassigned_mass=sum(
                d.demands.total_mass for d in simulator.unassigned_demands
            ),
        )
