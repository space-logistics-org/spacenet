"""
Object schemas for the results of demand analyses.
"""

from typing import List, Optional
from uuid import UUID

from fastapi_camelcase import CamelModel
from pydantic import Field

from ..schemas import ClassOfSupply, Environment
from .elements import SimElement
from .errors import SimDemand
from .network import SimLocation
from .resources import Demand, DemandSet, SimResource
from .simulator import DemandSimulator


class DemandLocation(CamelModel):
    """
    Location referenced by a demand.
    """

    id: UUID = Field(..., description="Unique identifier")
    name: str = Field(..., description="Location name")

    @classmethod
    def create(cls, location: Optional[SimLocation]) -> Optional["DemandLocation"]:
        """Creates a reference to a location."""
        if location is None:
            return None
        return cls(id=location.id, name=location.name)


class DemandElement(CamelModel):
    """
    Element referenced by a demand.
    """

    id: UUID = Field(..., description="Unique identifier")
    name: str = Field(..., description="Element name")

    @classmethod
    def create(cls, element: Optional[SimElement]) -> Optional["DemandElement"]:
        """Creates a reference to an element."""
        if element is None:
            return None
        return cls(id=element.id, name=element.name)


class DemandResourceType(CamelModel):
    """
    Resource type referenced by a demand.
    """

    type: str = Field(
        ..., description="Resource type (Generic, Continuous, or Discrete)"
    )
    name: str = Field(..., description="Resource name")
    class_of_supply: ClassOfSupply = Field(..., description="Class of supply")
    environment: Environment = Field(..., description="Required stowage environment")
    units: str = Field(..., description="Unit resource label")
    unit_mass: float = Field(..., description="Mass (kg) of 1.0 units")
    unit_volume: float = Field(..., description="Volume (m^3) of 1.0 units")
    packing_factor: float = Field(
        ..., description="Mass (kg) of packing material required per unit"
    )

    @classmethod
    def create(cls, resource: SimResource) -> "DemandResourceType":
        """Creates a description of a resource."""
        return cls(
            type=resource.resource_type,
            name=resource.name,
            class_of_supply=resource.class_of_supply,
            environment=resource.environment,
            units=resource.units,
            unit_mass=resource.unit_mass,
            unit_volume=resource.unit_volume,
            packing_factor=resource.packing_factor,
        )


class DemandResource(CamelModel):
    """
    Demanded (consumed or produced) amount of a resource.
    """

    resource: DemandResourceType = Field(..., description="Resource type")
    amount: float = Field(..., description="Absolute amount (units)")
    mass: float = Field(..., description="Mass (kg), negative if produced")
    volume: float = Field(..., description="Volume (m^3), negative if produced")

    @classmethod
    def create(cls, demand: Demand) -> "DemandResource":
        """Creates a description of a demand."""
        return cls(
            resource=DemandResourceType.create(demand.resource),
            amount=abs(demand.amount),
            mass=demand.mass,
            volume=demand.volume,
        )


class _DemandTotals(CamelModel):
    """
    Base class for a set of consumed and produced resources.
    """

    consumption: List[DemandResource] = Field([], description="Consumed resources")
    production: List[DemandResource] = Field([], description="Produced resources")
    total_consumption_mass: float = Field(0.0, description="Mass (kg) consumed")
    total_consumption_volume: float = Field(0.0, description="Volume (m^3) consumed")
    total_production_mass: float = Field(0.0, description="Mass (kg) produced")
    total_production_volume: float = Field(0.0, description="Volume (m^3) produced")

    def _set_demands(self, demands: DemandSet):
        self.consumption = [DemandResource.create(d) for d in demands if d.amount > 0]
        self.production = [DemandResource.create(d) for d in demands if d.amount < 0]
        self.total_consumption_mass = sum(r.mass for r in self.consumption)
        self.total_consumption_volume = sum(r.volume for r in self.consumption)
        self.total_production_mass = sum(r.mass for r in self.production)
        self.total_production_volume = sum(r.volume for r in self.production)
        return self


class RawDemand(_DemandTotals):
    """
    Demands generated by an element (or mission) at a time and location.
    """

    time: float = Field(..., description="Time (days) relative to the scenario start")
    location: Optional[DemandLocation] = Field(None, description="Demand location")
    element: Optional[DemandElement] = Field(
        None, description="Demanding element (undefined for mission-level demands)"
    )

    @classmethod
    def create(cls, demand: SimDemand) -> "RawDemand":
        """Creates a description of a logged demand."""
        # pylint: disable=protected-access
        return cls(
            time=demand.time,
            location=DemandLocation.create(demand.location),
            element=DemandElement.create(demand.element),
        )._set_demands(demand.demands)


class RawDemandsAnalysis(CamelModel):
    """
    Demands logged by a demand simulator.
    """

    demands: List[RawDemand] = Field([], description="Logged demands in order of time")

    @classmethod
    def create(cls, simulator: DemandSimulator) -> "RawDemandsAnalysis":
        """
        Creates a raw demands analysis from an executed demand simulator.

        Args:
            simulator (:obj:`DemandSimulator`): The demand simulator.

        Returns:
            :obj:`RawDemandsAnalysis`: The analysis results.
        """
        return cls(demands=[RawDemand.create(d) for d in simulator.unsatisfied_demands])


class NodeDemand(_DemandTotals):
    """
    Demands aggregated to the arrival of a transport at a node.
    """

    time: float = Field(
        ..., description="Arrival time (days) relative to the scenario start"
    )
    location: DemandLocation = Field(
        ..., description="Node at which demands are supplied"
    )


class EdgeDemand(_DemandTotals):
    """
    Demands aggregated to a transport along an edge.
    """

    start_time: float = Field(..., description="Departure time (days)")
    end_time: float = Field(..., description="Arrival time (days)")
    origin: DemandLocation = Field(..., description="Origin node of the edge")
    destination: DemandLocation = Field(..., description="Destination node of the edge")
    location: DemandLocation = Field(..., description="Edge along which demands occur")
    max_cargo_mass: float = Field(..., description="Cargo mass capacity (kg)")
    net_cargo_mass: float = Field(..., description="Unused cargo mass capacity (kg)")
    max_cargo_volume: float = Field(..., description="Cargo volume capacity (m^3)")
    net_cargo_volume: float = Field(
        ..., description="Unused cargo volume capacity (m^3)"
    )


class AggregatedDemandsAnalysis(CamelModel):
    """
    Demands aggregated to the transports from which they could be supplied.
    """

    nodes: List[NodeDemand] = Field([], description="Demands aggregated to nodes")
    edges: List[EdgeDemand] = Field([], description="Demands aggregated to edges")

    @classmethod
    def create(cls, simulator: DemandSimulator) -> "AggregatedDemandsAnalysis":
        """
        Creates an aggregated demands analysis from an executed demand simulator.

        Args:
            simulator (:obj:`DemandSimulator`): The demand simulator.

        Returns:
            :obj:`AggregatedDemandsAnalysis`: The analysis results.
        """
        # pylint: disable=protected-access
        return cls(
            nodes=[
                NodeDemand(
                    time=point.time, location=DemandLocation.create(point.node)
                )._set_demands(demands)
                for point, demands in simulator.aggregated_node_demands
            ],
            edges=[
                EdgeDemand(
                    start_time=edge.start_time,
                    end_time=edge.end_time,
                    origin=DemandLocation.create(edge.edge.origin),
                    destination=DemandLocation.create(edge.edge.destination),
                    location=DemandLocation.create(edge.edge),
                    max_cargo_mass=edge.max_cargo_mass,
                    net_cargo_mass=edge.net_cargo_mass,
                    max_cargo_volume=edge.max_cargo_volume,
                    net_cargo_volume=edge.net_cargo_volume,
                )._set_demands(demands)
                for edge, demands in simulator.aggregated_edge_demands
            ],
        )
